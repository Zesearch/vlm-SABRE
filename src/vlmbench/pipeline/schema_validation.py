"""Validate and load task-local schemas before they reach the OpenAI API."""

from __future__ import annotations

import ast
import importlib.util
import sys
import tempfile
import types
from pathlib import Path
from types import ModuleType
from typing import Any, Union, get_args, get_origin
from uuid import uuid4

from pydantic import BaseModel

from vlmbench.recipes.schema import BenchmarkDesign, QuestionSpec


class OpenAISchemaCompatibilityError(ValueError):
    """A model schema cannot be used with OpenAI strict structured outputs."""


_ALLOWED_IMPORTS = {
    "__future__": {"annotations"},
    "typing": {"List", "Literal"},
    "pydantic": {"Field"},
    "vlmbench.recipes.schema": {
        "BenchmarkDesign",
        "ReviewTarget",
        "StrictModel",
        "TaskAttribute",
    },
}
_ALLOWED_BASES = {"BenchmarkDesign", "StrictModel"}
_ALLOWED_FIELD_KEYWORDS = {
    "description",
    "ge",
    "gt",
    "le",
    "lt",
    "max_length",
    "min_length",
    "multiple_of",
    "pattern",
}


def _validate_annotation(node: ast.AST) -> None:
    allowed = (
        ast.Name,
        ast.Subscript,
        ast.Constant,
        ast.Tuple,
        ast.List,
        ast.Load,
        ast.BinOp,
        ast.BitOr,
    )
    for child in ast.walk(node):
        if not isinstance(child, allowed):
            raise ValueError(
                f"Unsupported schema annotation expression: {type(child).__name__}"
            )


def _validate_field_value(node: ast.AST | None) -> None:
    if node is None or isinstance(node, ast.Constant):
        return
    if not isinstance(node, ast.Call) or not isinstance(node.func, ast.Name):
        raise ValueError("Schema field defaults may only use constants or Field(...).")
    if node.func.id != "Field" or node.args:
        raise ValueError("Only keyword-only Field(...) constraints are allowed.")
    for keyword in node.keywords:
        if keyword.arg not in _ALLOWED_FIELD_KEYWORDS:
            raise ValueError(f"Unsupported Field(...) option: {keyword.arg}")
        if not isinstance(keyword.value, ast.Constant):
            raise ValueError("Field(...) constraint values must be constants.")


def validate_task_schema_source(source: str, *, class_name: str = "TaskDesign") -> None:
    """Accept only declarative Pydantic schema code generated by the agent."""

    try:
        tree = ast.parse(source)
    except SyntaxError as exc:
        raise ValueError(f"Generated task schema is not valid Python: {exc}") from exc

    declared_classes: set[str] = set()
    for statement in tree.body:
        if isinstance(statement, ast.Expr) and isinstance(statement.value, ast.Constant):
            if isinstance(statement.value.value, str):
                continue
        if isinstance(statement, ast.ImportFrom):
            allowed_names = _ALLOWED_IMPORTS.get(statement.module or "")
            imported_names = {alias.name for alias in statement.names}
            if (
                allowed_names is None
                or not imported_names <= allowed_names
                or any(alias.asname for alias in statement.names)
            ):
                raise ValueError(
                    f"Generated schema contains a disallowed import: {statement.module}"
                )
            continue
        if not isinstance(statement, ast.ClassDef):
            raise ValueError(
                "Generated schema may contain only imports and declarative class definitions."
            )
        if statement.decorator_list or statement.keywords:
            raise ValueError("Generated schema classes cannot use decorators or class keywords.")
        bases = {
            base.id for base in statement.bases if isinstance(base, ast.Name)
        }
        if len(bases) != len(statement.bases) or not bases <= _ALLOWED_BASES:
            raise ValueError(f"Unsupported base class on {statement.name}.")
        declared_classes.add(statement.name)
        for class_statement in statement.body:
            if isinstance(class_statement, ast.Expr) and isinstance(
                class_statement.value, ast.Constant
            ):
                if isinstance(class_statement.value.value, str):
                    continue
            if isinstance(class_statement, ast.Pass):
                continue
            if not isinstance(class_statement, ast.AnnAssign) or not isinstance(
                class_statement.target, ast.Name
            ):
                raise ValueError(
                    f"{statement.name} must contain only annotated field declarations."
                )
            _validate_annotation(class_statement.annotation)
            _validate_field_value(class_statement.value)

    if class_name not in declared_classes:
        raise ValueError(f"Generated schema must define class {class_name}.")


def _load_schema_module(path: Path) -> ModuleType:
    module_name = f"_vlmbench_task_schema_{uuid4().hex}"
    spec = importlib.util.spec_from_file_location(module_name, path)
    if spec is None or spec.loader is None:
        raise ImportError(f"Could not load schema module: {path}")
    module = importlib.util.module_from_spec(spec)
    sys.modules[module_name] = module
    try:
        spec.loader.exec_module(module)
    finally:
        sys.modules.pop(module_name, None)
    return module


def validate_openai_strict_model(model: type[BaseModel]) -> dict[str, Any]:
    """Return the SDK-normalized schema after enforcing OpenAI object constraints."""

    from openai.lib._pydantic import to_strict_json_schema

    schema = to_strict_json_schema(model)

    def walk(node: object, path: str) -> None:
        if isinstance(node, list):
            for index, item in enumerate(node):
                walk(item, f"{path}[{index}]")
            return
        if not isinstance(node, dict):
            return
        if node.get("type") == "object":
            properties = node.get("properties")
            if not isinstance(properties, dict):
                raise OpenAISchemaCompatibilityError(
                    f"{path}: dynamic object maps are not allowed; define fixed properties."
                )
            required = node.get("required")
            if not isinstance(required, list) or set(required) != set(properties):
                raise OpenAISchemaCompatibilityError(
                    f"{path}: required must contain every property exactly once."
                )
            if node.get("additionalProperties") is not False:
                raise OpenAISchemaCompatibilityError(
                    f"{path}: additionalProperties must be false."
                )
        for key, value in node.items():
            walk(value, f"{path}.{key}")

    walk(schema, model.__name__)
    return schema


def validate_downstream_design_contract(model: type[BenchmarkDesign]) -> None:
    """Ensure task-specific output can still be consumed by image construction."""

    base_fields = set(BenchmarkDesign.model_fields)
    task_fields = set(model.model_fields)
    if task_fields != base_fields:
        extra = sorted(task_fields - base_fields)
        missing = sorted(base_fields - task_fields)
        raise ValueError(
            "TaskDesign must preserve the BenchmarkDesign top-level envelope; "
            f"extra={extra}, missing={missing}. Put task-specific values in task_attributes."
        )

    annotation = model.model_fields["questions"].annotation
    if get_origin(annotation) is not list or len(get_args(annotation)) != 1:
        raise ValueError("TaskDesign.questions must be a list of concrete question models.")

    def question_models(value: object) -> list[type[BaseModel]]:
        origin = get_origin(value)
        if origin in {Union, types.UnionType}:
            models: list[type[BaseModel]] = []
            for option in get_args(value):
                models.extend(question_models(option))
            return models
        if isinstance(value, type) and issubclass(value, BaseModel):
            return [value]
        raise ValueError("TaskDesign.questions must use concrete Pydantic question models.")

    allowed = set(QuestionSpec.model_fields)
    required_core = allowed - {"options"}
    for question_model in question_models(get_args(annotation)[0]):
        fields = set(question_model.model_fields)
        if not required_core <= fields or not fields <= allowed:
            raise ValueError(
                f"{question_model.__name__} must use only the stable question envelope; "
                f"fields={sorted(fields)}."
            )


def load_task_schema_file(
    path: Path,
    *,
    class_name: str = "TaskDesign",
) -> type[BenchmarkDesign]:
    source = path.read_text(encoding="utf-8")
    validate_task_schema_source(source, class_name=class_name)
    module = _load_schema_module(path)
    schema = getattr(module, class_name, None)
    if not isinstance(schema, type) or not issubclass(schema, BenchmarkDesign):
        raise TypeError(f"{path}:{class_name} must subclass BenchmarkDesign.")
    validate_downstream_design_contract(schema)
    validate_openai_strict_model(schema)
    return schema


def validate_task_schema_text(
    source: str,
    *,
    class_name: str = "TaskDesign",
) -> type[BenchmarkDesign]:
    validate_task_schema_source(source, class_name=class_name)
    with tempfile.TemporaryDirectory() as directory:
        path = Path(directory) / "schema.py"
        path.write_text(source, encoding="utf-8")
        return load_task_schema_file(path, class_name=class_name)
